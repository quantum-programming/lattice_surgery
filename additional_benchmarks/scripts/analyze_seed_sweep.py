"""Generate the manuscript statistics table from the saved seed sweep."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
report = json.loads((ROOT / "seed_sweep.json").read_text())
summaries = {
    (row["benchmark"], row["tool"]): row for row in report["summaries"]
    if row["tool"] != "paired_statistics"
}


def pm(metric: dict[str, float], digits: int = 1) -> str:
    return f"${metric['mean']:.{digits}f} \\pm {metric['sample_sd']:.{digits}f}$"


lines = [
    r"% Generated by scripts/analyze_seed_sweep.py.",
    r"\begin{table*}[t]",
    r"    \centering",
    r"    \setlength{\tabcolsep}{10pt}",
    r"    \caption{Results over five paired circuit-generation seeds, reported as mean $\pm$ sample standard deviation.",
    r"    Both methods have 49 available spatial sites.",
    r"    Native depth is the discrete time extent reported by each compiler; temporal extent and occupied volume are measured from the exported TQEC BlockGraph.}",
    r"    \label{tab:topols_seed_sweep}",
    r"    \begin{tabular}{llrrrr}",
    r"        \toprule",
    r"        Circuit & Method & $n$ & Native depth & Temporal extent & Occupied volume \\",
    r"        \midrule",
]
for family, label in (("mqt_max_parallel", "Max-parallel"),
                      ("mqt_min_parallel", "Min-parallel")):
    for tool, method in (("this_work", "Double-slice"), ("topols", "TopoLS")):
        row = summaries[(family, tool)]
        lines.append(
            f"        {label} & {method} & {row['n']} & "
            f"{pm(row['native_depth'])} & {pm(row['tqec_time_extent'])} & "
            f"{pm(row['tqec_occupied_volume'])}" + r" \\")
lines += [r"        \bottomrule", r"    \end{tabular}", r"\end{table*}"]
destination = ROOT / "figures" / "seed_sweep_comparison.tex"
destination.write_text("\n".join(lines) + "\n", newline="\n")
print(destination)
