"""Reproduce the manuscript table using TQEC's official BlockGraph metrics.

Reads results/*.bgraph and comparison.json, without rerunning compilation.
Writes figures/block_graph_comparison.tex.
"""
import json
from pathlib import Path

from tqec import BlockGraph

ROOT = Path(__file__).resolve().parents[1]

# BlockGraph tutorial (cubes, pipes and a CNOT example):
# https://tqec.github.io/tqec/user_guide/build_computation.html
# Official metric definitions: tqec/computation/block_graph.py.
# spacetime_volume excludes ports and pipes; bounding_box_size includes ports.
recorded = json.loads((ROOT / "comparison.json").read_text())["rows"]
lines = [
    r"% Generated by scripts/analyze_structure.py.",
    r"\begin{table}[t]",
    r"    \centering",
    r"    \caption{Comparison on the two eight-qubit CNOT circuits.",
    r"    Sites denotes the available spatial allocation.",
    r"    TQEC's bounding-box dimensions $(x, y, z)$ include input/output ports, with $z$ denoting the time-coordinate extent.",
    r"    $V$ is TQEC's spacetime volume, which sums occupied computation and storage cubes and excludes ports and pipes.}",
    r"    \label{tab:topols_comparison}",
    r"    \begin{tabular}{llrrr}",
    r"        \toprule",
    r"        Circuit & Method & Sites & $(x, y, z)$ & $V$ \\",
    r"        \midrule",
]
for row in recorded:
    name = row["benchmark"]
    ours = row["tool"] == "this_work"
    tool = "ours" if ours else "topols"
    graph = BlockGraph.from_bgraph(ROOT / "results" / f"{tool}-{name}.bgraph")
    graph.validate()
    dimensions = graph.bounding_box_size()
    volume = graph.spacetime_volume
    # Check that saved graphs and recorded metrics belong to consistent results.
    assert list(dimensions) == row["tqec"]["bounding_box"]
    assert volume == row["tqec"]["occupied_volume"]
    # Available sites are compiler settings, not the occupied graph's footprint.
    sites = row["allocated_sites"] if ours else row["spatial_footprint"]
    label = "Max-parallel" if name == "mqt_max_parallel" else "Min-parallel"
    method = "Double-slice" if ours else "TopoLS"
    x, y, z = dimensions
    lines.append(f"        {label} & {method} & {sites} & $({x}, {y}, {z})$ & {volume:g}" + r" \\")
lines += [r"        \bottomrule", r"    \end{tabular}", r"\end{table}"]
destination = ROOT / "figures" / "block_graph_comparison.tex"
destination.write_text("\n".join(lines) + "\n", newline="\n")
print(destination)
