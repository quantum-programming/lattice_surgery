"""Generate the manuscript statistics table from the saved circuit seeds."""
import json
import statistics
from pathlib import Path
from typing import Any

from comparison_common import FAMILIES, SEEDS

ROOT = Path(__file__).resolve().parents[1]


def mean_sd(values: list[float]) -> dict[str, float]:
    return {
        "mean": statistics.mean(values),
        "sample_sd": statistics.stdev(values),
        "min": min(values),
        "max": max(values),
    }


def summarize(rows: list[dict[str, Any]]) -> tuple[list[int], list[dict[str, Any]]]:
    passed = [row for row in rows if row["status"] == "passed"]
    complete_seeds = sorted(
        seed for seed in SEEDS
        if all(
            any(row["seed"] == seed and row["benchmark"] == family
                and row["tool"] == tool for row in passed)
            for family in FAMILIES for tool in ("this_work", "topols")
        )
    )
    summaries = []
    for family in FAMILIES:
        family_rows = [row for row in passed if row["benchmark"] == family
                       and row["seed"] in complete_seeds]
        paired = {row["seed"]: row for row in family_rows
                  if row["tool"] == "this_work"}
        topols_rows = [row for row in family_rows if row["tool"] == "topols"]
        for tool in ("this_work", "topols"):
            selected = [row for row in family_rows if row["tool"] == tool]
            summaries.append({
                "benchmark": family,
                "tool": tool,
                "n": len(selected),
                "tqec_occupied_volume": mean_sd(
                    [row["tqec"]["occupied_volume"] for row in selected]),
                "total_execution_time": mean_sd(
                    [row["total_execution_time"] for row in selected]),
                "compilation_seconds": mean_sd(
                    [row["compilation_seconds"] for row in selected]),
            })
        volume_reductions = [
            100 * (1 - paired[row["seed"]]["tqec"]["occupied_volume"]
                   / row["tqec"]["occupied_volume"])
            for row in topols_rows
        ]
        time_reductions = [
            100 * (1 - paired[row["seed"]]["total_execution_time"]
                   / row["total_execution_time"])
            for row in topols_rows
        ]
        speedups = [
            row["compilation_seconds"] / paired[row["seed"]]["compilation_seconds"]
            for row in topols_rows
        ]
        summaries.append({
            "benchmark": family,
            "tool": "paired_statistics",
            "n": len(volume_reductions),
            "tqec_occupied_volume_reduction_percent": mean_sd(volume_reductions),
            "total_execution_time_reduction_percent": mean_sd(time_reductions),
            "compilation_speedup": mean_sd(speedups),
        })
    return complete_seeds, summaries


def pm(metric: dict[str, float], digits: int = 1) -> str:
    return f"${metric['mean']:.{digits}f} \\pm {metric['sample_sd']:.{digits}f}$"


def main() -> None:
    report_path = ROOT / "circuit_seeds.json"
    report = json.loads(report_path.read_text())
    complete_seeds, summary_rows = summarize(report["rows"])
    report["complete_seeds"] = complete_seeds
    report["excluded_failures"] = [
        row for row in report["rows"] if row["status"] != "passed"
    ]
    report["summaries"] = summary_rows
    report_path.write_text(json.dumps(report, indent=2) + "\n")

    summaries = {
        (row["benchmark"], row["tool"]): row for row in summary_rows
        if row["tool"] != "paired_statistics"
    }
    lines = [
        r"% Generated by scripts/analyze_circuit_seeds.py.",
        r"\begin{table*}[t]",
        r"    \centering",
        r"    \setlength{\tabcolsep}{10pt}",
        r"    \caption{Results over " + str(len(complete_seeds))
        + r" paired circuit-generation seeds, reported as mean $\pm$ sample standard deviation.",
        r"    Total execution time is reported in code beats by each compiler. Occupied volume is measured from the exported TQEC BlockGraph.}",
        r"    \label{tab:topols_circuit_seeds}",
        r"    \begin{tabular}{llrrr}",
        r"        \toprule",
        r"        Circuit & Method & $n$ & Total execution time & Occupied volume \\",
        r"        \midrule",
    ]
    for family, label in (("mqt_max_parallel", "Max-parallel"),
                          ("mqt_min_parallel", "Min-parallel")):
        for tool, method in (("this_work", "Double-slice"), ("topols", "TopoLS")):
            row = summaries[(family, tool)]
            lines.append(
                f"        {label} & {method} & {row['n']} & "
                f"{pm(row['total_execution_time'])} & "
                f"{pm(row['tqec_occupied_volume'])}" + r" \\")
    lines += [r"        \bottomrule", r"    \end{tabular}", r"\end{table*}"]
    destination = ROOT / "figures" / "circuit_seeds_comparison.tex"
    destination.write_text("\n".join(lines) + "\n", newline="\n")
    print(destination)


if __name__ == "__main__":
    main()
